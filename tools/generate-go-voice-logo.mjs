#!/usr/bin/env bun
// Derives all brand artwork from the left round mark of assets/brand/yz-logo-source.png
// (519x143, white on transparent): transparent logo PNG, macOS app icon, firmware RGB565 header.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const src = resolve(root, 'assets/brand/yz-logo-source.png');
const logo = resolve(root, 'assets/brand/go-voice-logo.png');
const icon = resolve(root, 'gui/resources/icon.png');
const caption = resolve(root, 'assets/brand/yiyan-caption.png');
const dir = mkdtempSync(join(tmpdir(), 'yz-logo-'));
const ff = (args, o = {}) => {
  const r = spawnSync('ffmpeg', ['-nostdin', '-v', 'error', '-y', ...args], { maxBuffer: 1 << 26, ...o });
  if (r.status !== 0) throw new Error(String(r.stderr || r.error));
  return r.stdout;
};
try {
  // Round mark only: 143x143 at the left edge, upscaled to 1024.
  ff(['-i', src, '-vf', 'crop=143:143:0:0,scale=1024:1024:flags=lanczos,format=rgba', '-frames:v', '1', logo]);
  // App icon: the transparent mark with a small margin, no background tile.
  ff(['-i', logo, '-vf', 'scale=880:880:flags=lanczos,format=rgba,pad=1024:1024:72:72:color=0x00000000', '-frames:v', '1', icon]);
  // Firmware: 64x64 RGB565 over UI_BG.
  const pixels = ff(['-i', logo, '-filter_complex',
    '[0:v]scale=64:64:flags=lanczos,format=rgba[l];color=c=0x0B1018:s=64x64,format=rgba[bg];[bg][l]overlay=shortest=1,format=rgb565le[out]',
    '-map', '[out]', '-frames:v', '1', '-f', 'rawvideo', 'pipe:1']);
  if (pixels.length !== 8192) throw new Error(`Unexpected raster size: ${pixels.length}`);
  const toRows = (buf) => {
    const out = [];
    for (let o = 0; o < buf.length; o += 16)
      out.push('    ' + [...buf.subarray(o, o + 16)].map(n => `0x${n.toString(16).padStart(2, '0')}`).join(', ') + ',');
    return out.join('\n');
  };
  // Caption "伊言" (56x28, rendered by tools/render-brand-caption.swift) over UI_BG.
  const captionPixels = ff(['-i', caption, '-filter_complex',
    '[0:v]format=rgba[l];color=c=0x0B1018:s=56x28,format=rgba[bg];[bg][l]overlay=shortest=1,format=rgb565le[out]',
    '-map', '[out]', '-frames:v', '1', '-f', 'rawvideo', 'pipe:1']);
  if (captionPixels.length !== 56 * 28 * 2) throw new Error(`Unexpected caption size: ${captionPixels.length}`);
  const hash = new Bun.CryptoHasher('sha256').update(readFileSync(src)).digest('hex');
  writeFileSync(resolve(root, 'assets/brand/go_voice_logo_asset.h'),
    `#pragma once
#include <stdint.h>

/* YZ round logo mark and the "伊言" caption. Generated by tools/generate-go-voice-logo.mjs.
 * Source SHA-256: ${hash}
 * RGB565 little-endian, alpha composited onto UI_BG (#0B1018).
 * Logo 64x64 (8192 bytes), caption 56x28 (3136 bytes); no runtime resize, decode, or heap allocation.
 */
static const uint8_t s_go_voice_logo_data[8192] = {
${toRows(pixels)}
};

static const uint8_t s_yiyan_caption_data[3136] = {
${toRows(captionPixels)}
};
`);
} finally { rmSync(dir, { recursive: true, force: true }); }
console.log('Generated logo, app icon and firmware asset');
